// 能力水平参考（百分制）
export function abilityLevel(percentage) {
  if (percentage >= 85) return { level: '较强', desc: '能独立分析复杂问题，发现规律，建立模型并设计清晰算法' };
  if (percentage >= 70) return { level: '良好', desc: '基本掌握计算思维方法，能够解决常见问题' };
  if (percentage >= 60) return { level: '中等', desc: '有一定意识，但在抽象、流程设计或规律迁移方面不够稳定' };
  return { level: '需要加强', desc: '容易混淆任务关系，难以提取规律或形成完整解决步骤' };
}
